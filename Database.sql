CREATE TRIGGER CADERNETA_CLIENTE_BIU0 FOR CADERNETA_CLIENTE BEFORE INSERT OR UPDATE
AS
  declare variable id_temp type of column temporadas.id_temporadas;
begin
  if (new.fk_temporada is null) then
  begin
    if (new.fk_pedido is not null) then
    begin
      select
        p.fk_temporada
      from
        pedido p
      where
        p.id_pedido = new.fk_pedido
      into
        :id_temp;
    end
    else begin
      select
        t.id_temporadas
      from
        temporadas t
      where
        t.ativo
      into
        :id_temp ;
    end
    new.fk_temporada = :id_temp;
  end
end;

