CREATE OR ALTER PROCEDURE PR_VENDAS_ACOMULADO RETURNS (
	DIA_MOV DATE,
	ANTERIOR NUMERIC(18,2),
	VENDAS NUMERIC(18,2),
	PAGAMENTOS NUMERIC(18,2),
	ARECEBER NUMERIC(18,2),
	VENDAS_ACOM NUMERIC(18,2)
)
AS
declare DESCONTO NUMERIC(18,2);
  declare DESC_ACOM NUMERIC(18,2);
  declare VENDA_DIA NUMERIC(18,2);
begin
  :ANTERIOR = 0;
  :desc_acom = 0;
  :vendas_acom = 0;
  :areceber= 0 ;
  FOR select distinct
      mv.dia_mov,
      sum(iif(mv.pagamento, 0, mv.valor_total)) vendas,
      sum(iif(mv.pagamento and mv.tipo_pagamento <> 5, mv.valor_total * -1, 0)) pagamentos,
      sum(iif(mv.pagamento and mv.tipo_pagamento = 5, mv.valor_total * -1, 0)) descontos
    from
      mov_produto mv
    where
        not mv.excluido and
        mv.dia_mov between
              (select
                 t.periodo_inicial
               from
                 temporadas t
               where
                   t.ativo)
               and (select
                       coalesce(t.periodo_final, current_date)
                     from
                       temporadas t
                     where
                         t.ativo)
          group by
              dia_mov
          order by
              mv.dia_mov
  into
    :dia_mov,
    :venda_dia,
    :pagamentos,
    :desconto
  do
  BEGIN
    :vendas = :venda_dia-:desconto;
    :areceber = :areceber +:vendas-:pagamentos;
    :desc_acom = :desc_acom + :desconto;
    :vendas_acom = :vendas_acom + :vendas;
    suspend;
    :anterior=:vendas_acom;
  END
end;


CREATE TRIGGER TR_TEMPOR_ATIVO FOR TEMPORADAS AFTER INSERT OR UPDATE
AS
begin
  if (new.ativo) then
  begin
    update temporadas t
    set
      t.ativo = false
    where
      T.ativo
      and t.id_temporadas <> new.id_temporadas;
  end
end;

CREATE TRIGGER TR_TEMPOR_DATA_FIM FOR TEMPORADAS AFTER INSERT
AS
begin
  update temporadas t
  set t.periodo_final = dateadd(day, -1, cast(new.periodo_inicial as date))
  where t.periodo_final is null and
        t.periodo_inicial < dateadd(day, -1, cast(new.periodo_inicial as date)) ;
end;

CREATE TRIGGER CADERNETA_CLIENTE_AI0 FOR CADERNETA_CLIENTE AFTER INSERT
